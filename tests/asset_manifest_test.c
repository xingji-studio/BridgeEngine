#include "BridgeEngine.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifdef _WIN32
#include <direct.h>
#include <process.h>
#include <windows.h>
#else
#include <sys/stat.h>
#include <sys/types.h>
#include <unistd.h>
#endif

static int failures = 0;

static void check(int condition, const char *message)
{
	if (!condition) {
		fprintf(stderr, "FAIL: %s\n", message);
		failures++;
	}
}

static long test_process_id(void)
{
#ifdef _WIN32
	return (long)_getpid();
#else
	return (long)getpid();
#endif
}

static int test_mkdir(const char *path)
{
#ifdef _WIN32
	return _mkdir(path);
#else
	return mkdir(path, 0700);
#endif
}

static int test_remove_file(const char *path)
{
	return remove(path);
}

static int test_remove_dir(const char *path)
{
#ifdef _WIN32
	return _rmdir(path);
#else
	return rmdir(path);
#endif
}

static int write_text(const char *path, const char *text)
{
	FILE *file = fopen(path, "wb");
	if (file == NULL) return -1;
	size_t length = strlen(text);
	if (fwrite(text, 1, length, file) != length) {
		fclose(file);
		return -1;
	}
	return fclose(file);
}

static void make_temp_dir(char *out, size_t capacity)
{
#ifdef _WIN32
	char  base[MAX_PATH];
	DWORD length = GetTempPathA((DWORD)sizeof(base), base);
	if (length == 0 || length >= sizeof(base)) snprintf(base, sizeof(base), ".");
	const char *root = base;
#else
	const char *root = getenv("TMPDIR");
	if (root == NULL || root[0] == '\0') root = "/tmp";
#endif
	for (int attempt = 0; attempt < 100; attempt++) {
		snprintf(out, capacity, "%s/bapi_asset_manifest_%ld_%d", root, test_process_id(), attempt);
		if (test_mkdir(out) == 0) return;
	}
	out[0] = '\0';
}

static int file_exists(const char *path)
{
	FILE *file = fopen(path, "rb");
	if (file == NULL) return 0;
	fclose(file);
	return 1;
}

static void test_null_handling(void)
{
	bapi_clear_last_error();
	check(bapi_asset_manifest_load(NULL) == NULL, "load rejects NULL path");
	check(bapi_get_last_error()[0] != '\0', "load NULL path sets last error");

	bapi_clear_last_error();
	check(bapi_asset_manifest_count(NULL) == 0, "count(NULL) is 0");
	check(bapi_get_last_error()[0] != '\0', "count(NULL) sets last error");

	check(bapi_asset_manifest_get(NULL, 0) == NULL, "get(NULL) returns NULL");
	check(bapi_asset_manifest_first_missing(NULL) == NULL, "first_missing(NULL) is NULL");

	int checked = 7;
	bapi_clear_last_error();
	check(bapi_asset_manifest_verify(NULL, "/tmp", &checked) == -1, "verify(NULL) fails");
	check(checked == 0, "verify(NULL) clears checked");
	check(bapi_get_last_error()[0] != '\0', "verify(NULL) sets last error");

	bapi_asset_manifest_destroy(NULL);
	check(1, "destroy(NULL) is a no-op");
}

static void test_invalid_headers(const char *directory)
{
	char path[1024];
	snprintf(path, sizeof(path), "%s/bad_magic.txt", directory);
	write_text(path, "NOPE 1\nasset foo.txt\n");
	bapi_clear_last_error();
	check(bapi_asset_manifest_load(path) == NULL, "load rejects bad magic");
	check(strstr(bapi_get_last_error(), "BASSETS") != NULL, "bad magic error mentions BASSETS");
	test_remove_file(path);

	snprintf(path, sizeof(path), "%s/version_zero.txt", directory);
	write_text(path, "BASSETS 0\nasset foo.txt\n");
	check(bapi_asset_manifest_load(path) == NULL, "load rejects version 0");
	test_remove_file(path);

	snprintf(path, sizeof(path), "%s/version_99.txt", directory);
	write_text(path, "BASSETS 99\nasset foo.txt\n");
	check(bapi_asset_manifest_load(path) == NULL, "load rejects version 99");
	test_remove_file(path);

	snprintf(path, sizeof(path), "%s/no_header.txt", directory);
	write_text(path, "# only a comment\n\n");
	check(bapi_asset_manifest_load(path) == NULL, "load rejects a manifest without a header");
	test_remove_file(path);

	snprintf(path, sizeof(path), "%s/empty.txt", directory);
	write_text(path, "");
	check(bapi_asset_manifest_load(path) == NULL, "load rejects an empty file");
	test_remove_file(path);
}

static void test_load_and_verify(const char *directory)
{
	char manifest_path[1024];
	char present_path[1024];
	char missing_dir[1024];
	char missing_path[1024];
	char empty_path[1024];

	snprintf(manifest_path, sizeof(manifest_path), "%s/assets.manifest", directory);
	snprintf(present_path, sizeof(present_path), "%s/present.txt", directory);
	snprintf(missing_dir, sizeof(missing_dir), "%s/missing", directory);
	snprintf(missing_path, sizeof(missing_path), "%s/missing/item.txt", directory);
	snprintf(empty_path, sizeof(empty_path), "%s/empty.manifest", directory);

	write_text(present_path, "present");
	write_text(manifest_path, "# generated by the test\n"
							  "BASSETS 1\n"
							  "   # indented comment\n"
							  "\n"
							  "asset present.txt # inline comment\n"
							  "unknown_key ignored value\n"
							  "asset missing/item.txt\n");

	bapi_asset_manifest_t manifest = bapi_asset_manifest_load(manifest_path);
	check(manifest != NULL, "load reads a valid manifest");
	if (manifest == NULL) return;

	check(bapi_asset_manifest_count(manifest) == 2, "count reports two entries");
	check(strcmp(bapi_asset_manifest_get(manifest, 0), "present.txt") == 0,
		  "get(0) returns the first entry");
	check(strcmp(bapi_asset_manifest_get(manifest, 1), "missing/item.txt") == 0,
		  "get(1) returns the second entry");
	check(bapi_asset_manifest_get(manifest, 2) == NULL, "get past the end returns NULL");
	check(bapi_asset_manifest_get(manifest, -1) == NULL, "get(-1) returns NULL");

	int checked = -1;
	int missing = bapi_asset_manifest_verify(manifest, directory, &checked);
	check(missing == 1, "verify counts the missing entry");
	check(checked == 2, "verify reports the entry count");
	check(bapi_asset_manifest_first_missing(manifest) != NULL,
		  "first_missing reports a path after a failed verify");
	check(strcmp(bapi_asset_manifest_first_missing(manifest), "missing/item.txt") == 0,
		  "first_missing is the first missing entry");

	check(test_mkdir(missing_dir) == 0, "create the missing directory");
	write_text(missing_path, "now present");

	missing = bapi_asset_manifest_verify(manifest, directory, &checked);
	check(missing == 0, "verify succeeds once every entry exists");
	check(checked == 2, "verify keeps reporting the entry count");
	check(bapi_asset_manifest_first_missing(manifest) == NULL,
		  "verify resets first_missing when nothing is missing");

	write_text(empty_path, "BASSETS 1\n");
	bapi_asset_manifest_t empty = bapi_asset_manifest_load(empty_path);
	check(empty != NULL, "load accepts an empty manifest");
	if (empty != NULL) {
		check(bapi_asset_manifest_count(empty) == 0, "empty manifest has zero entries");
		checked = -1;
		check(bapi_asset_manifest_verify(empty, directory, &checked) == 0,
			  "empty manifest verifies clean");
		check(checked == 0, "empty manifest reports zero checked");
		check(bapi_asset_manifest_first_missing(empty) == NULL,
			  "empty manifest has no first_missing");
		bapi_asset_manifest_destroy(empty);
	}

	bapi_asset_manifest_destroy(manifest);
	test_remove_file(missing_path);
	test_remove_dir(missing_dir);
	test_remove_file(empty_path);
	test_remove_file(manifest_path);
	test_remove_file(present_path);
}

static void test_null_root(const char *directory)
{
	char manifest_path[1024];
	char entry[128];
	char probe_path[1024];
	char text[512];

	snprintf(entry, sizeof(entry), "bapi_asset_manifest_probe_%ld", test_process_id());
	snprintf(manifest_path, sizeof(manifest_path), "%s/null_root.manifest", directory);
	snprintf(text, sizeof(text), "BASSETS 1\nasset %s\n", entry);
	write_text(manifest_path, text);

	bapi_asset_manifest_t manifest = bapi_asset_manifest_load(manifest_path);
	check(manifest != NULL, "load null-root manifest");
	if (manifest != NULL) {
		int checked = 0;
		check(bapi_asset_manifest_verify(manifest, NULL, &checked) == 1,
			  "NULL root checks the current directory");
		check(checked == 1, "NULL root reports one checked entry");
		check(bapi_asset_manifest_verify(manifest, "", &checked) == 1,
			  "empty root checks the current directory");
		check(checked == 1, "empty root reports one checked entry");
		bapi_asset_manifest_destroy(manifest);
	}

	/* Absolute entries do not get prefixed by the root. */
	snprintf(probe_path, sizeof(probe_path), "%s/%s", directory, entry);
	write_text(probe_path, "probe");
	snprintf(manifest_path, sizeof(manifest_path), "%s/null_root_present.manifest", directory);
	snprintf(text, sizeof(text), "BASSETS 1\nasset %s/%s\n", directory, entry);
	write_text(manifest_path, text);

	manifest = bapi_asset_manifest_load(manifest_path);
	check(manifest != NULL, "load absolute-entry manifest");
	if (manifest != NULL) {
		int checked = 0;
		check(bapi_asset_manifest_verify(manifest, "/nonexistent-root", &checked) == 0,
			  "absolute entries ignore the root prefix");
		check(checked == 1, "absolute entry is checked");
		check(file_exists(probe_path), "absolute probe file exists");
		bapi_asset_manifest_destroy(manifest);
	}

	test_remove_file(probe_path);
	test_remove_file(manifest_path);
	snprintf(manifest_path, sizeof(manifest_path), "%s/null_root.manifest", directory);
	test_remove_file(manifest_path);
}

int main(void)
{
	char directory[1024];
	make_temp_dir(directory, sizeof(directory));
	if (directory[0] == '\0') {
		fprintf(stderr, "FAIL: cannot create a temporary directory\n");
		return 1;
	}

	test_null_handling();
	test_invalid_headers(directory);
	test_load_and_verify(directory);
	test_null_root(directory);

	test_remove_dir(directory);
	if (failures == 0) printf("asset manifest test: ok\n");
	return failures == 0 ? 0 : 1;
}
